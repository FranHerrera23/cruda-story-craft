// Bundles portal/app.js and portal/portal.css into portal/assets.generated.ts.
// Run after editing either file:  node scripts/build-portal-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const js = readFileSync('portal/app.js', 'utf8')
const css = readFileSync('portal/portal.css', 'utf8')
writeFileSync('portal/assets.generated.ts', `// Generated by scripts/build-portal-assets.mjs. Edit portal/app.js and portal/portal.css instead.\nexport const PORTAL_JS = ${JSON.stringify(js)}\nexport const PORTAL_CSS = ${JSON.stringify(css)}\n`)
console.log('portal assets bundled')
